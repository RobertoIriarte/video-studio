import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { projectInputFixture } from '@video-studio/testkit';

test.use({ baseURL: 'http://127.0.0.1:4174' });
const fixtureProject = '00000000-0000-4000-8000-00000000a301';
test('F3-04 · jobs reales de fixture, revisión exacta, polling y controles recuperables', async ({ page }) => {
  test.setTimeout(150000);
  await page.goto('/generations');
  await page.getByLabel('Correo', { exact: true }).fill('production-e2e@example.invalid');
  await page.getByLabel('Contraseña', { exact: true }).fill(process.env.VIDEO_STUDIO_E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Generaciones', exact: true })).toBeVisible();
  await expect(page.locator('article.production-job')).toHaveCount(25);
  await page.getByRole('button', { name: 'Siguiente página', exact: true }).click();
  await expect(page.locator('article.production-job')).toHaveCount(1);
  await page.getByRole('button', { name: 'Volver al inicio', exact: true }).click();
  let releaseRead: () => void = () => undefined;
  const readGate = new Promise<void>((resolve) => { releaseRead = resolve; });
  await page.route('**/api/v1/jobs?status=FAILED', async (route) => { const response = await route.fetch(); await readGate; await route.fulfill({ response }); }, { times: 1 });
  await page.getByRole('combobox', { name: 'Estado', exact: true }).selectOption('FAILED');
  await expect(page.getByText('Cargando trabajos…', { exact: true })).toBeVisible();
  await expect(page.locator('article.production-job')).toHaveCount(0); // No presentar los resultados del filtro anterior.
  releaseRead();
  await expect(page.locator('article.production-job')).toHaveCount(1);
  await page.getByRole('link', { name: 'Ver intentos', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Historial de intentos', exact: true })).toBeVisible();
  await expect(page.getByText('Intento 1', { exact: true })).toBeVisible();
  await page.goto('/generations?status=FAILED');
  await page.getByRole('button', { name: 'Solicitar reintento', exact: true }).click();
  await page.getByRole('button', { name: 'Confirmar reintento', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'No hay trabajos con estos filtros', exact: true })).toBeVisible();

  await page.goto(`/projects/${fixtureProject}`);
  await expect(page.getByRole('heading', { name: 'Producción de prueba · simulación', exact: true })).toBeVisible();
  await expect(page.getByText(/26 registrados/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Revisar versión 1', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Revisar versión 2', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Contenido de revisión de la versión 2');
  await page.getByRole('button', { name: 'Aprobar versión 2', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Revisar versión 2', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Pausar coordinación', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Reanudar coordinación', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Reanudar coordinación', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pausar coordinación', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/production-overview.png' });

  await page.getByRole('link', { name: 'Proveedores', exact: true }).click();
  await page.getByLabel('Nombre de la vía manual', { exact: true }).fill('Vía manual E2E');
  await page.getByRole('button', { name: 'Guardar vía manual', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Vía manual E2E', exact: true })).toBeVisible();
  await page.getByLabel('Prioridad de Vía manual E2E', { exact: true }).fill('0');
  const manualCard = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Vía manual E2E', exact: true }) });
  await manualCard.getByRole('button', { name: 'Guardar prioridad', exact: true }).click();
  await expect(manualCard.getByRole('button', { name: 'Guardar prioridad', exact: true })).toBeDisabled();
  const configs = await (await page.request.get('/api/v1/providers')).json() as { items: { id: string; name: string }[] };
  const manualId = configs.items.find((p) => p.name === 'Vía manual E2E')!.id;
  const input = projectInputFixture({ title: 'Coordinación manual E2E' }); input.settings.providerPolicy.preferredIds = [manualId];
  const draftResponse = await page.request.post('/api/v1/projects', { headers: { origin: 'http://127.0.0.1:4174', 'idempotency-key': crypto.randomUUID() }, data: { ...input, wizardStep: 5 } });
  expect(draftResponse.status()).toBe(201); const draft = await draftResponse.json() as { id: string };
  await page.goto(`/projects/${draft.id}`);
  await page.getByRole('button', { name: 'Iniciar producción', exact: true }).click();
  await page.keyboard.press('Escape'); await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Iniciar producción', exact: true }).click();
  // El servidor confirma pero se pierde la respuesta: reintento usa key y payload originales.
  await page.route(`**/api/v1/projects/${draft.id}/start`, async (route) => { await route.fetch(); await route.abort('failed'); }, { times: 1 });
  await page.getByRole('button', { name: 'Confirmar inicio', exact: true }).click();
  const startDialog = page.getByRole('dialog');
  await expect(startDialog.getByRole('button', { name: 'Reintentar operación', exact: true })).toBeVisible();
  await startDialog.getByRole('button', { name: 'Reintentar operación', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByText(/0 trabajos terminados de 1 registrados/)).toBeVisible();
  await expect(page.locator('article.production-job').getByText('Esperando resultado manual', { exact: true })).toBeVisible();

  await page.goto('/generations'); await expect(page.locator('article.production-job')).toHaveCount(25);
  await page.route('**/api/v1/jobs?*', async (route) => route.fulfill({ status: 503, json: { error: { code: 'SERVICE_UNAVAILABLE', message: 'Fallo temporal de prueba.', requestId: crypto.randomUUID(), retryable: true } } }), { times: 1 });
  await page.getByRole('button', { name: 'Actualizar', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Fallo temporal de prueba.' })).toBeVisible();
  await expect(page.locator('article.production-job')).toHaveCount(25);
  await page.getByRole('button', { name: 'Actualizar', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Fallo temporal de prueba.' })).toHaveCount(0);
  await page.clock.install();
  let requests = 0; page.on('request', (request) => { if (request.url().includes('/api/v1/jobs?')) requests++; });
  await page.evaluate(() => { Object.defineProperty(document, 'visibilityState', { value: 'hidden', configurable: true }); document.dispatchEvent(new Event('visibilitychange')); });
  const hiddenCount = requests; await page.clock.runFor(60000); expect(requests).toBe(hiddenCount);
  await page.evaluate(() => { delete (document as unknown as Record<string, unknown>).visibilityState; document.dispatchEvent(new Event('visibilitychange')); });
  await expect.poll(() => requests).toBeGreaterThan(hiddenCount);
  await page.context().setOffline(true); await expect(page.getByRole('alert').filter({ hasText: 'Sin conexión' })).toBeVisible();
  const offlineCount = requests; await page.clock.runFor(60000); expect(requests).toBe(offlineCount);
  await page.context().setOffline(false); await expect.poll(() => requests).toBeGreaterThan(offlineCount);
  await expect(page.getByRole('alert').filter({ hasText: 'Sin conexión' })).toHaveCount(0);
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
  await page.screenshot({ path: 'test-results/generations.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/generations-mobile.png' });
  await page.reload(); await expect(page.getByRole('heading', { name: 'Generaciones', exact: true })).toBeVisible();
  await expect(page.locator('article.production-job')).toHaveCount(25);
});
