CREATE TABLE scene_versions (
  id TEXT PRIMARY KEY NOT NULL CHECK(length(id)=36 AND substr(id,9,1)='-' AND substr(id,14,1)='-' AND substr(id,19,1)='-' AND substr(id,24,1)='-' AND length(replace(id,'-',''))=32 AND lower(replace(id,'-','')) NOT GLOB '*[^0-9a-f]*'),
  project_id TEXT NOT NULL,
  scene_id TEXT NOT NULL,
  script_version_id TEXT NOT NULL,
  parent_version_id TEXT,
  version_no INTEGER NOT NULL CHECK(typeof(version_no)='integer' AND version_no BETWEEN 1 AND 9007199254740991),
  narration TEXT NOT NULL,
  direction_json TEXT NOT NULL CHECK(json_valid(direction_json) AND json_type(direction_json)='object'),
  duration_ms INTEGER NOT NULL CHECK(typeof(duration_ms)='integer' AND duration_ms BETWEEN 1 AND 9007199254740991),
  generation_scope TEXT NOT NULL CHECK(generation_scope IN ('ALL','VISUAL','NARRATION','VOICE','MUSIC','AMBIENCE','EDIT')),
  status TEXT NOT NULL CHECK(status IN ('DRAFT','CANDIDATE','APPROVED','SUPERSEDED','INVALIDATED')),
  hash TEXT NOT NULL CHECK(length(hash)=64 AND hash NOT GLOB '*[^0-9a-f]*'),
  created_at TEXT NOT NULL CHECK(strftime('%Y-%m-%dT%H:%M:%fZ',created_at) IS NOT NULL AND strftime('%Y-%m-%dT%H:%M:%fZ',created_at)=created_at),
  UNIQUE(scene_id,version_no),
  UNIQUE(id,project_id),
  UNIQUE(id,scene_id,project_id),
  FOREIGN KEY(scene_id,project_id) REFERENCES scenes(id,project_id) ON DELETE RESTRICT,
  FOREIGN KEY(script_version_id,project_id) REFERENCES script_versions(id,project_id) ON DELETE RESTRICT,
  FOREIGN KEY(parent_version_id,scene_id,project_id) REFERENCES scene_versions(id,scene_id,project_id) ON DELETE RESTRICT);
