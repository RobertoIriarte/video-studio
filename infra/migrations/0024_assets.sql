CREATE TABLE assets (
  id TEXT PRIMARY KEY NOT NULL CHECK(length(id)=36 AND substr(id,9,1)='-' AND substr(id,14,1)='-' AND substr(id,19,1)='-' AND substr(id,24,1)='-' AND length(replace(id,'-',''))=32 AND lower(replace(id,'-','')) NOT GLOB '*[^0-9a-f]*'),
  project_id TEXT NOT NULL,
  owner_id TEXT NOT NULL,
  type TEXT NOT NULL CHECK(type IN ('IMAGE','VIDEO','AUDIO')),
  mime TEXT NOT NULL CHECK(mime IN ('image/png','image/jpeg','image/webp','video/mp4','audio/mpeg','audio/wav','audio/ogg') AND mime LIKE lower(type)||'/%'),
  bytes INTEGER NOT NULL CHECK(typeof(bytes)='integer' AND bytes BETWEEN 1 AND 9007199254740991),
  checksum TEXT NOT NULL CHECK(length(checksum)=64 AND checksum NOT GLOB '*[^0-9a-f]*'),
  duration_ms INTEGER CHECK(duration_ms IS NULL OR (typeof(duration_ms)='integer' AND duration_ms BETWEEN 1 AND 9007199254740991)),
  width INTEGER CHECK(width IS NULL OR (typeof(width)='integer' AND width BETWEEN 1 AND 9007199254740991)),
  height INTEGER CHECK(height IS NULL OR (typeof(height)='integer' AND height BETWEEN 1 AND 9007199254740991)),
  origin TEXT NOT NULL CHECK(origin IN ('MANUAL','PROVIDER')),
  provider_id TEXT,
  generation_id TEXT,
  license_json TEXT NOT NULL CHECK(json_valid(license_json) AND json_type(license_json)='object'),
  prompt TEXT,
  r2_key TEXT,
  availability TEXT NOT NULL CHECK(availability IN ('MISSING','LOCAL_ONLY','REMOTE_AVAILABLE','BOTH')),
  created_at TEXT NOT NULL CHECK(strftime('%Y-%m-%dT%H:%M:%fZ',created_at) IS NOT NULL AND strftime('%Y-%m-%dT%H:%M:%fZ',created_at)=created_at),
  UNIQUE(id,project_id),
  FOREIGN KEY(project_id,owner_id) REFERENCES projects(id,owner_id) ON DELETE RESTRICT);
